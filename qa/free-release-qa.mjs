import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const read = path => fs.readFileSync(path, 'utf8');
const root = read('index.html');
const tools = read('tools/index.html');
const freePath = 'downloads/Calculator_Suite_Free_v1.0.0.html';
const free = read(freePath);
const products = read('products/index.html');
const flag = JSON.parse(read('data/storefront-mode.json'));
let checks = 0;
const ok = (value, message) => { assert.ok(value, message); checks++; };
const href = '/downloads/Calculator_Suite_Free_v1.0.0.html';

ok(flag.productsVisible === false, 'All paid products must remain hidden');
ok(products.includes('عرض المنتجات متوقف حاليًا'), 'Do not unpause the products route');
ok(products.includes('noindex,nofollow'), 'Paid product catalog must remain noindex');
ok(root.includes('href="' + href + '"'), 'Homepage Free download is missing');
ok(tools.includes('href="' + href + '"'), 'Tools page Free download is missing');
ok(root.includes('download="Calculator_Suite_Free_v1.0.0.html"'), 'Homepage must download, not just navigate');
ok(tools.includes('download="Calculator_Suite_Free_v1.0.0.html"'), 'Tool hub must download, not just navigate');
ok(free.includes('Calculator Suite Free v1.0.0'), 'Free edition/version is missing');
ok(free.includes('حاسبة تسعير المنتج'), 'Basic pricing calculator missing');
ok(free.includes('حاسبة نقطة التعادل'), 'Break-even calculator missing');
ok(free.includes('بدون اشتراك') || free.includes('دون اشتراك'), 'No-subscription policy missing');
ok(free.includes('بدون تثبيت') || free.includes('دون اشتراك أو اتصال'), 'Offline instructions missing');
ok(free.includes('استفسر عن الترقية عبر واتساب'), 'Optional upgrade link missing');
ok(free.includes('https://wa.me/201011673107'), 'Wrong upgrade phone');
ok(!/<script[^>]+src=/i.test(free), 'Free app must not load external scripts');
ok(!/<link[^>]+rel="stylesheet"/i.test(free), 'Free app must not require external CSS');
ok(!/\b(fetch|XMLHttpRequest|WebSocket)\s*\(/.test(free), 'Free app unexpectedly needs an API/network');
ok(!/DELIVERY_ADMIN_TOKEN|PRIVATE_FILES/i.test(free), 'Worker secrets/bindings must not be included');
ok(!/\/products\//.test(root) && !/\/products\//.test(tools), 'Paid products must not be linked from public Free promotions');
ok(!/calculator-suite-starter|calculator-suite-professional/.test(root + tools), 'No paid SKU exposed on public pages');
ok(!/\.(zip|7z|rar)["']/.test(root + tools), 'No paid archive URLs');
ok(!fs.existsSync('downloads/starter.zip') && !fs.existsSync('downloads/professional.zip'), 'Paid products must not be in downloads');
ok(fs.statSync(freePath).size < 100000, 'Free download too large');
const scripts = [...free.matchAll(/<script>([\s\S]*?)<\/script>/g)];
ok(scripts.length === 1, 'Free app must have one self-contained script');
new vm.Script(scripts[0][1], { filename: freePath }); checks++;
console.log('PASS ' + checks + ' free-download safety and packaging checks; paid products remain hidden');
